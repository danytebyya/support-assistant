IDENTITY_RE = re.compile(r"\b(кто ты|ты кто|представься|как тебя зовут)\b", re.I)
GREETING_RE = re.compile(
    r"^\s*(?:здравствуй(?:те)?|привет(?:ствую)?|доброе\s+(?:утро|день)|добрый\s+вечер)[!,.?\s]*$",
    re.I,
)
CAPABILITIES_RE = re.compile(
    r"\b(что (?:ты )?(?:делаешь|умеешь|можешь)|чем (?:ты )?занимаешься|как ты можешь помочь)\b",
    re.I,
)
PRIVATE_RE = re.compile(
    r"(\bмодел(?:ь|и|ью|ях|ей)\b|\bнейросет\w*\b|\bllm\b|\bollama\b|"
    r"\bты\b.{0,35}\b(openai|chatgpt|deepseek|дипсик|qwen|llama|gemma|mistral)\b|"
    r"\b(openai|chatgpt|deepseek|дипсик|qwen|llama|gemma|mistral)\b.{0,35}\bты\b|"
    r"на чем ты работаешь|как ты работаешь|"
    r"системн\w+ (промпт|сообщен)|покажи.*(инструкц|настройк)|"
    r"внутренн\w+ (устройств|архитектур|реализац|настройк)|"
    r"(архитектур|реализац).{0,25}(ассистент|систем)|что у тебя внутри|раскрой.*промпт)", re.I
)
INJECTION_RE = re.compile(
    r"(игнорируй|забудь|отмени|сбрось).{0,35}(инструкц|правил|промпт)|"
    r"\b(?:ignore|disregard|forget|override|bypass)\b.{0,35}\b(?:instruction|rule|prompt|system)s?\b|"
    r"(?:developer|system)\s*(?:message|prompt|mode)|jailbreak|режим разработчика", re.I
)
DOMAIN_RE = re.compile(
    r"(lime|лайм|\bтв\b|телеканал|канал|эфир|приложен|сайт|подписк|платеж|оплат|"
    r"регистрац|авторизац|аккаунт|профил|парол|(?:смс.?код|код (?:входа|подтверждения))|плеер|видео|звук|трансляц|"
    r"телепрограмм|передач|архив|избранн|качеств|разрешени|\b(?:240|360|480|720|1080)[рp]\b|"
    r"android|iphone|ios|телевизор|приставк|windows|smart)", re.I
)


def fixed_answer(message: str) -> str | None:
    text = " ".join(message.split())
    if GREETING_RE.fullmatch(text):
        return GREETING
    if PRIVATE_RE.search(text) or INJECTION_RE.search(text):
        return PRIVATE
    if IDENTITY_RE.search(text):
        return IDENTITY
    if CAPABILITIES_RE.search(text):
        return CAPABILITIES
    return None


def likely_in_domain(message: str) -> bool:
    return bool(DOMAIN_RE.search(message))


